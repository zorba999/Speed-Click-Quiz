// LOBBY
// ═══════════════════════════════════════════════════════════════════════
function Lobby({ room, isHost, myAddress, onStart, onLeave, showToast }) {
  const [players, setPlayers] = useState(() => {
    // start with host (me) + 2 mock joiners
    return [
      myAddress || MOCK_ADDRS[0],
      MOCK_ADDRS[1],
      MOCK_ADDRS[2],
    ];
  });
  const [busy, setBusy] = useState(false);

  // Simulate players joining
  useEffect(() => {
    const id = setTimeout(() => {
      if (players.length < Math.min(5, room.players)) {
        setPlayers(p => [...p, MOCK_ADDRS[(p.length) % MOCK_ADDRS.length]]);
      }
    }, 4500);
    return () => clearTimeout(id);
  }, [players, room.players]);

  async function handleStart() {
    setBusy(true);
    showToast('AI generating questions on-chain…');
    await new Promise(r => setTimeout(r, 1500));
    onStart();
    setBusy(false);
  }

  const inviteUrl = `speed.click/r/${room.code}`;

  return (
    <div>
      <button className="btn btn-ghost btn-sm mb-24" onClick={onLeave}>← LEAVE</button>

      <div className="lobby-grid">
        <div className="room-code-card">
          <div className="row-between" style={{ position: 'relative' }}>
            <span className="kicker">/ ROOM CODE</span>
            <span className="chip chip-amber">
              <span className="pulse" style={{ width: 6, height: 6, borderRadius: '50%', background: 'var(--amber)' }} />
              WAITING
            </span>
          </div>
          <div className="room-code-display">{room.code}</div>

          <div className="invite-bar">
            <span className="url">{inviteUrl}</span>
            <button className="btn btn-sm btn-ghost" onClick={() => { navigator.clipboard?.writeText(inviteUrl); showToast('Invite link copied'); }}>
              ⧉ COPY
            </button>
          </div>

          <div className="row gap-16 mt-24" style={{ flexWrap: 'wrap' }}>
            <span className="chip">⏱ {room.rounds} rounds</span>
            <span className="chip">⌬ {players.length}/{room.players} joined</span>
            <span className="chip chip-accent">⚡ AI on Bradbury</span>
          </div>

          {isHost ? (
            <button
              className="btn btn-primary btn-lg mt-24"
              style={{ width: '100%' }}
              onClick={handleStart}
              disabled={busy || players.length < 2}
            >
              {busy
                ? <><span className="spinner" /> GENERATING QUESTIONS…</>
                : players.length < 2
                  ? `WAITING FOR PLAYERS · ${players.length}/2 MIN`
                  : `START GAME · ${players.length} PLAYERS ⚡`}
            </button>
          ) : (
            <div className="mt-24 center text-muted" style={{ fontSize: '0.85rem' }}>
              <span className="spinner" /> Waiting for host to start the game…
            </div>
          )}
        </div>

        <div className="card">
          <div className="row-between mb-16">
            <span className="kicker">/ PLAYERS</span>
            <span className="mono text-muted" style={{ fontSize: '0.78rem' }}>{players.length}/{room.players}</span>
          </div>
          <div className="col gap-8">
            {Array.from({ length: room.players }).map((_, i) => {
              const addr = players[i];
              if (!addr) {
                return (
                  <div key={i} className="player-slot empty">
                    <span className="text-muted mono center" style={{ fontSize: '1rem' }}>—</span>
                    <span className="text-muted mono">empty slot</span>
                    <span className="mono" style={{ fontSize: '0.7rem', color: 'var(--muted)' }}>idle</span>
                  </div>
                );
              }
              const me = addr === myAddress;
              const host = i === 0;
              return (
                <div key={addr+i} className={`player-slot${me ? ' me' : ''}${host ? ' host' : ''} anim-up`}>
                  <Avatar addr={addr} name={nick(addr)} />
                  <div>
                    <div className="name">{nick(addr)}{me ? ' · YOU' : ''}</div>
                    <div className="addr">{shortAddr(addr)}</div>
                  </div>
                </div>
              );
            })}
          </div>
        </div>
      </div>
    </div>
  );
}

