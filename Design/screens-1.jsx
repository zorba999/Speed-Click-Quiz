// JOIN ROOM
// ═══════════════════════════════════════════════════════════════════════
function JoinRoom({ onBack, onJoined, showToast }) {
  const [code, setCode] = useState('');
  const [busy, setBusy] = useState(false);

  async function handleJoin() {
    if (!code.trim()) return;
    setBusy(true);
    await new Promise(r => setTimeout(r, 800));
    showToast('Joined room ✓');
    onJoined({ code: code.toUpperCase() });
    setBusy(false);
  }

  return (
    <div style={{ maxWidth: 560, margin: '0 auto' }}>
      <button className="btn btn-ghost btn-sm mb-24" onClick={onBack}>← BACK</button>
      <span className="kicker">/ JOIN A GAME</span>
      <h1 className="display display-lg mt-12 mb-24">Drop the code.</h1>

      <div className="card">
        <div className="field mb-16">
          <label className="field-label">Room code</label>
          <input
            autoFocus
            className="input input-big"
            placeholder="GLITCH-NEON-42"
            value={code}
            onChange={e => setCode(e.target.value.toUpperCase().replace(/[^A-Z0-9-]/g,''))}
          />
        </div>
        <button
          className="btn btn-magenta btn-lg"
          style={{ width: '100%' }}
          disabled={busy || !code.trim()}
          onClick={handleJoin}
        >
          {busy ? <><span className="spinner" /> JOINING…</> : 'JOIN ROOM →'}
        </button>
      </div>
    </div>
  );
}

